    private fun getTasksFromResources(context: Context, mode: GameMode): List<Task> {
        val arrayResId = when (mode) {
            GameMode.CHILDREN -> R.array.tasks_children
            GameMode.TEEN -> R.array.tasks_teen
            GameMode.ADULT -> R.array.tasks_adult
            GameMode.ADULT_PLUS -> R.array.tasks_adult_plus
            GameMode.SEX -> R.array.tasks_sex
        }

        return try {
            val stringArray = context.resources.getStringArray(arrayResId)
            Logger.d("TasksProvider", "Loaded ${stringArray.size} tasks for mode: $mode, language: ${Locale.getDefault().language}")

            if (mode == GameMode.SEX) {
                getSexTasksWithImages(context)
            } else {
                stringArray.map { Task(it) }
            }
        } catch (e: Exception) {
            Logger.e("TasksProvider", "Failed to get tasks for mode: $mode", e)
            getFallbackTasks(mode)
        }
    }

